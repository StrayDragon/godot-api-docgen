    public enum ShadowmaskMode : long
    {
        /// <summary>
        /// <para>Shadowmasking is disabled. No shadowmask texture will be created when baking lightmaps. Existing shadowmask textures will be removed during baking.</para>
        /// </summary>
        None = 0,
        /// <summary>
        /// <para>Shadowmasking is enabled. Directional shadows that are outside the <see cref="Godot.DirectionalLight3D.DirectionalShadowMaxDistance"/> will be rendered using the shadowmask texture. Shadows that are inside the range will be rendered using real-time shadows exclusively. This mode allows for more precise real-time shadows up close, without the potential "smearing" effect that can occur when using lightmaps with a high texel size. The downside is that when the camera moves fast, the transition between the real-time light and shadowmask can be obvious. Also, objects that only have shadows baked in the shadowmask (and no real-time shadows) won't display any shadows up close.</para>
        /// </summary>
        Replace = 1,
        /// <summary>
        /// <para>Shadowmasking is enabled. Directional shadows will be rendered with real-time shadows overlaid on top of the shadowmask texture. This mode makes for smoother shadow transitions when the camera moves fast, at the cost of a potential smearing effect for directional shadows that are up close (due to the real-time shadow being mixed with a low-resolution shadowmask). Objects that only have shadows baked in the shadowmask (and no real-time shadows) will keep their shadows up close.</para>
        /// </summary>
        Overlay = 2
    }

